-- Stage 2: enforce due dates for manual charges.
-- Existing charges remain unchanged.
-- Automatic billing functions are not rewritten.
BEGIN;
SET LOCAL lock_timeout = '5s';

DO $preflight$
DECLARE
  monthly_owner text;
  penalty_owner text;
BEGIN
  SELECT pg_catalog.pg_get_userbyid(proowner)
  INTO monthly_owner
  FROM pg_catalog.pg_proc
  WHERE oid = to_regprocedure('public.bill_monthly_dues(date)')
    AND prosecdef;

  SELECT pg_catalog.pg_get_userbyid(proowner)
  INTO penalty_owner
  FROM pg_catalog.pg_proc
  WHERE oid = to_regprocedure('public.post_due_penalties(bigint)')
    AND prosecdef;

  IF monthly_owner IS NULL OR penalty_owner IS NULL
     OR monthly_owner NOT IN ('postgres', 'supabase_admin')
     OR penalty_owner NOT IN ('postgres', 'supabase_admin') THEN
    RAISE EXCEPTION
      'Unrecognized billing-function security ownership; stop Stage 2.';
  END IF;
END;
$preflight$;

CREATE OR REPLACE FUNCTION public.require_manual_charge_due_date()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $trigger$
DECLARE
  monthly_owner text;
  penalty_owner text;
BEGIN
  -- Monthly HOA dues may be created without a custom deadline
  -- only by the trusted automatic billing execution context.
  IF NEW.billing_month IS NOT NULL THEN
    SELECT pg_catalog.pg_get_userbyid(proowner)
    INTO monthly_owner
    FROM pg_catalog.pg_proc
    WHERE oid = to_regprocedure('public.bill_monthly_dues(date)')
      AND prosecdef;

    IF NEW.charge_type = 'Association Dues'
       AND NEW.due_date IS NULL
       AND NEW.created_by IS NULL
       AND NEW.created_by_name = 'System (automatic)'
       AND monthly_owner IN ('postgres', 'supabase_admin')
       AND current_user = monthly_owner THEN
      RETURN NEW;
    END IF;

    RAISE EXCEPTION
      'Only trusted automatic HOA dues can specify billing_month.';
  END IF;

  -- Manual charges have an inclusive final deadline.
  IF NEW.due_date IS NOT NULL THEN
    IF NEW.due_date < public.hoa_manila_today() THEN
      RAISE EXCEPTION
        'New manual charges cannot have a past final due date.';
    END IF;

    RETURN NEW;
  END IF;

  -- Automatic annual penalties are generated by a trusted
  -- SECURITY DEFINER routine, including staff-invoked runs.
  SELECT pg_catalog.pg_get_userbyid(proowner)
  INTO penalty_owner
  FROM pg_catalog.pg_proc
  WHERE oid = to_regprocedure('public.post_due_penalties(bigint)')
    AND prosecdef;

  IF NEW.charge_type = 'Penalty / Late Fee'
     AND NEW.created_by_name IN (
       'System (automatic)',
       'System (staff-triggered)'
     )
     AND NEW.description LIKE 'Annual compound penalty %'
     AND penalty_owner IN ('postgres', 'supabase_admin')
     AND current_user = penalty_owner THEN
    RETURN NEW;
  END IF;

  RAISE EXCEPTION
    'A final due date is required for manual charges.';
END;
$trigger$;

REVOKE ALL ON FUNCTION public.require_manual_charge_due_date()
FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS require_manual_charge_due_date
ON public.property_charges;

CREATE TRIGGER require_manual_charge_due_date
BEFORE INSERT ON public.property_charges
FOR EACH ROW
EXECUTE FUNCTION public.require_manual_charge_due_date();

COMMIT;
