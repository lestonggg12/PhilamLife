-- Record the serial already printed on physical stock, without editing any
-- payment/service transaction or recalculating its amounts.
begin;
create table public.receipt_paper_numbers (
  id uuid primary key default gen_random_uuid(),
  payment_id bigint unique references public.payments(id) on delete restrict,
  service_transaction_id uuid unique references public.service_transactions(id) on delete restrict,
  invoice_number text not null check (invoice_number ~ '^[0-9]{1,20}$' and invoice_number ~ '[1-9]'),
  assigned_by uuid not null default auth.uid(),
  assigned_at timestamptz not null default now(),
  constraint receipt_paper_numbers_one_receipt check (
    (payment_id is not null)::integer + (service_transaction_id is not null)::integer = 1
  )
);
-- Leading zeroes may be displayed, but cannot make the same physical serial
-- available twice across homeowner and service receipts (3464 = 003464).
create unique index receipt_paper_numbers_serial_unique
  on public.receipt_paper_numbers (ltrim(invoice_number, '0'));
alter table public.receipt_paper_numbers enable row level security;
revoke all on public.receipt_paper_numbers from public, anon, authenticated;
grant select, insert on public.receipt_paper_numbers to authenticated;
grant all on public.receipt_paper_numbers to service_role;
create policy "Staff can read paper invoice numbers" on public.receipt_paper_numbers
  for select to authenticated
  using ((select public.current_user_role()) in ('admin','secretary','treasurer'));
create policy "Staff can assign paper invoice numbers" on public.receipt_paper_numbers
  for insert to authenticated
  with check (assigned_by = (select auth.uid()) and
    (select public.current_user_role()) in ('admin','secretary','treasurer'));
-- Staff cannot silently reassign a physical number. Corrections need an
-- administrator-reviewed database change; the financial receipt is untouched.
create function public.audit_paper_invoice_number()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null or new.assigned_by is distinct from auth.uid()
    or coalesce(public.current_user_role(), '') not in ('admin','secretary','treasurer') then
    raise exception 'A signed-in staff member must assign the paper invoice number.';
  end if;
  insert into public.activity_log(user_id, action, target)
  values(new.assigned_by, 'Paper Invoice Number Assigned',
    'Invoice ' || new.invoice_number || ' — ' ||
    case when new.payment_id is not null then 'payment ' || new.payment_id::text
      else 'service receipt ' || new.service_transaction_id::text end);
  return new;
end;
$$;
revoke all on function public.audit_paper_invoice_number() from public, anon, authenticated;
create trigger audit_paper_invoice_number after insert on public.receipt_paper_numbers
  for each row execute function public.audit_paper_invoice_number();
comment on table public.receipt_paper_numbers is
  'Preprinted paper serials assigned to saved homeowner/service receipts. These numbers are not generated by the app and do not change receipt amounts.';
commit;
